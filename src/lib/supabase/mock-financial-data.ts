/**
 * Identifica se um registro financeiro, de reembolso ou de ponto faz parte da
 * base simulada de demonstração (prefixo "sim-") ou se é um lançamento real.
 */
export function isSimulatedRecord(id?: string | null): boolean {
  if (!id) return false;
  return id.startsWith('sim-');
}

